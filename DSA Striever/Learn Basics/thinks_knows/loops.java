public class loops {
    public static void main(String [] args){


// For loop
        for(int i = 0; i < 10; i++){
            System.out.println("My name is Suman");
        }

        // while loop -
        int i = 0;
        while(i < 10){
            System.out.println("Preparing for java");
            i++;
        }

        //  do while 1 time condition will run - if it is false also -
        
        int j = 2;
        do 
        {
            System.out.println("This is Do while loop");
            j = j + 1;
        } while(j <= 1);
        System.out.print(j);
    }
}
